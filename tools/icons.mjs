// Writes space/icons.js from the remixicon package (a dev dependency): the
// icons every button and mark of an editor, the maps and a maps site draws.
// Only the names below, each in its line and fill style. Run by the build;
// the output is committed, so no page loads anything from the package or
// from remote.
//
//   node tools/icons.mjs
import { readFileSync, readdirSync, writeFileSync, copyFileSync } from 'node:fs'
import { join } from 'node:path'

const NAMES = [
  'add', 'arrow-down', 'arrow-down-s', 'arrow-go-back', 'arrow-left-double', 'arrow-left-right',
  'arrow-left-s', 'arrow-right-double', 'arrow-right-s', 'check', 'close', 'cloudy', 'contrast',
  'dice-5', 'error-warning', 'flag', 'focus-3', 'global', 'hexagon', 'layout-grid', 'moon',
  'palette', 'pause', 'pencil', 'planet', 'play', 'refresh', 'route', 'sparkling', 'star', 'sun',
  'font-size', 'share', 'haze', 'stack',
]

const PACKAGE = 'node_modules/remixicon'
const OUT = 'viewer/space/icons.js'
const version = JSON.parse(readFileSync(join(PACKAGE, 'package.json'), 'utf-8')).version

// Every file of the package by its name: the icons sit in category folders.
const files = new Map()
for (const category of readdirSync(join(PACKAGE, 'icons'))) {
  for (const file of readdirSync(join(PACKAGE, 'icons', category))) files.set(file, join(PACKAGE, 'icons', category, file))
}

// What is inside the <svg>: every Remix icon is drawn on 0 0 24 24 in currentColor.
function inner(file) {
  const svg = readFileSync(file, 'utf-8')
  if (!svg.includes('viewBox="0 0 24 24"')) throw new Error(`${file}: not on the 24px grid`)
  return svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim()
}

const icons = {}
for (const name of NAMES) {
  icons[name] = {}
  for (const style of ['line', 'fill']) {
    // The editor's icons come in one style only (font-size): that one for both.
    const file = files.get(`${name}-${style}.svg`) || files.get(`${name}.svg`)
    if (!file) throw new Error(`remixicon ${version} has no ${name}-${style}`)
    icons[name][style] = inner(file)
  }
}

writeFileSync(OUT, `// Remix Icon ${version} (Apache 2.0, see icons.LICENSE): the icons of every
// button and mark. Generated by tools/icons.mjs (npm run icons) — do not
// edit by hand.
//
// ICONS is plain JSON between its braces, so a host can read this same file
// for its own pages.
export const ICONS = ${JSON.stringify(icons, null, 1)}

/* An icon as an <svg>, in the text colour and 1em square (.ic): the line
 * style, or the fill one for a pressed toggle. aria-hidden: the button's own
 * title and aria-label say what it does. */
export function icon(name, { filled = false } = {}) {
  const paths = ICONS[name]
  if (!paths) throw new Error('No icon ' + name)
  return '<svg class="ic" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" focusable="false" data-icon="' +
    name + '">' + paths[filled ? 'fill' : 'line'] + '</svg>'
}

/* A toggle's icon: the line style, the fill one while aria-pressed is true —
 * the state in the shape as well as the colour. Kept so as the button's
 * aria-pressed changes, wherever that is set. The button. */
export function toggleIcon(button, name) {
  const draw = () => { button.innerHTML = icon(name, { filled: button.getAttribute('aria-pressed') === 'true' }) }
  draw()
  new MutationObserver(draw).observe(button, { attributes: true, attributeFilter: ['aria-pressed'] })
  return button
}

/* An icon with a small plus at its lower right: add a ring, add a moon. */
export function iconAdd(name) {
  return '<span class="ic-add">' + icon(name) + '<span class="ic-badge">' + icon('add') + '</span></span>'
}
`)
copyFileSync(join(PACKAGE, 'License'), OUT.replace(/\.js$/, '.LICENSE'))
console.log(`${OUT}: ${NAMES.length} icons from remixicon ${version}`)
